async function seed() {
  try {
    await sequelize.authenticate();
    console.log('✅  Connexion DB OK\n');

    let inserted = 0, skipped = 0;

    for (const club of CLUBS) {
      const existing = await Team.findOne({
        where: sequelize.where(
          sequelize.fn('LOWER', sequelize.col('name')),
          club.name.toLowerCase()
        ),
      });

      if (existing) {
        process.stdout.write(`⏭️  Existant : ${club.name}\n`);
        skipped++;
        continue;
      }

      await Team.create({
        name:        club.name,
        shortName:   club.short,
        isActive:    true,
        description: 'Club de la Ligue de Football Casablanca',
      });

      process.stdout.write(`✅  Inséré  : ${club.name}\n`);
      inserted++;
    }

    console.log('\n──────────────────────────────────────');
    console.log(`✅  ${inserted} clubs insérés`);
    console.log(`⏭️   ${skipped} clubs déjà existants`);
    console.log(`📊  Total : ${inserted + skipped} / ${CLUBS.length}`);

  } catch (err) {
    console.error('❌  Erreur :', err.message);
  } finally {
    await sequelize.close();
  }
}

seed();
